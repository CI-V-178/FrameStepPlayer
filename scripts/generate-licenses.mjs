import * as checker from "license-checker-rseidelsohn";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const packages = await new Promise((resolve, reject) =>
  checker.init(
    {
      start: root,
      production: true,
      excludePrivatePackages: true,
      customFormat: { name: "", version: "", copyright: "", licenseText: "" },
    },
    (error, result) => (error ? reject(error) : resolve(result)),
  ),
);
const entries = [];
for (const [key, pkg] of Object.entries(packages).sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const text = (
    pkg.licenseText ||
    (pkg.licenseFile ? await readFile(pkg.licenseFile, "utf8") : "")
  ).trim();
  if (!text) throw new Error("License text not found: " + key);
  const copyright = (
    pkg.copyright ||
    text
      .split("\n")
      .filter((line) => /copyright|©/i.test(line))
      .join(" ")
  ).trim();
  if (!copyright) throw new Error("Copyright not found: " + key);
  entries.push({
    name: pkg.name || key.slice(0, key.lastIndexOf("@")),
    version: pkg.version || key.slice(key.lastIndexOf("@") + 1),
    license: String(pkg.licenses),
    copyright,
    text,
  });
}
for (const [name, file] of [
  ["Noto Sans JP", "NotoSansJP-OFL.txt"],
  ["JetBrains Mono", "JetBrainsMono-OFL.txt"],
  ["Roboto", "Roboto-OFL.txt"],
]) {
  const text = (
    await readFile(new URL("licenses/" + file, import.meta.url), "utf8")
  ).trim();
  entries.push({
    name,
    version: "Google Fonts distribution",
    license: "OFL-1.1",
    copyright: text.split("\n")[0],
    text,
  });
}
const header =
  "# Third-party notices\n\nGenerated by npm run licenses using license-checker-rseidelsohn (production dependencies, including transitive dependencies) and the bundled official font license files. Do not edit by hand.\n";
const cell = (s) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const table =
  "\n| Package / Font | Version | License | Copyright |\n|---|---|---|---|\n" +
  entries
    .map(
      (e) =>
        "| " +
        [e.name, e.version, e.license, e.copyright].map(cell).join(" | ") +
        " |",
    )
    .join("\n") +
  "\n";
const details = entries
  .map(
    (e) =>
      "\n## " +
      e.name +
      " " +
      e.version +
      "\n\nLicense: " +
      e.license +
      "\n\n" +
      e.text +
      "\n",
  )
  .join("\n");
await writeFile(
  new URL("../THIRD_PARTY_NOTICES.md", import.meta.url),
  header + table + details,
);
await writeFile(
  new URL("../public/licenses.txt", import.meta.url),
  header.replace(/^# /, "") + table + details,
);
console.log(
  entries.map((e) => e.name + "@" + e.version + ": " + e.license).join("\n"),
);
const review = entries.filter((e) =>
  /\b(?:A?GPL|LGPL|MPL|EPL|CDDL)|UNKNOWN|UNLICENSED/i.test(e.license),
);
console.log(
  "License review required: " +
    (review.map((e) => e.name + " (" + e.license + ")").join(", ") || "none"),
);
